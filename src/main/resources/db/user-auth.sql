-- Run once as the database owner before starting the application.
-- Existing records keep NULL user_id and are not visible to any account.
BEGIN;

CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

ALTER TABLE public.budgets
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES public.app_users(id);
ALTER TABLE public.categories
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES public.app_users(id);
ALTER TABLE public.expenses
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES public.app_users(id);

-- The configured application role needs to read users and register accounts.
GRANT SELECT, INSERT ON TABLE public.app_users TO finance_user;
GRANT USAGE, SELECT ON SEQUENCE public.app_users_id_seq TO finance_user;

COMMIT;
